<script setup>
import { ref, computed } from 'vue'
import { Download, FileCode2, Image, Printer, Shapes, Package, Maximize2, Minimize2, CheckCircle2, Workflow } from 'lucide-vue-next'
import { db, l1Caps, saveDiagram } from '../store'
import { buildStatesModel, transitions, plateauSummary, changesCsv, modelToDiagrams } from '../archimate/states'
import { viewToSvg, svgToPng } from '../archimate/svgRender'
import { modelToOpenExchangeXml } from '../archimate/notation'
import { toDrawio, statesToDrawioPages } from '../archimate/drawio'
import { money, fmtMonth } from '../utils/format'
import { download } from '../utils/excel'
import PageHead from '../components/PageHead.vue'
import EntityChip from '../components/EntityChip.vue'

// ---- options
const scopeIds = ref([])
const onlyChanges = ref(false)
const showStatus = ref(true)
const showRemoved = ref(true)
const fit = ref(true)
const toggleScope = id => { const i = scopeIds.value.indexOf(id); i >= 0 ? scopeIds.value.splice(i, 1) : scopeIds.value.push(id) }

const model = computed(() => buildStatesModel({ l1Ids: scopeIds.value, onlyChanges: onlyChanges.value, showRemoved: showRemoved.value && showStatus.value }))
const active = ref('view-overview')
const view = computed(() => model.value.views.find(v => v.id === active.value) || model.value.views[0])
const today = new Date().toISOString().slice(0, 10)
const svgOf = v => viewToSvg(v, model.value, {
  showStatus: showStatus.value,
  title: (v.kind === 'overview' ? `Migration overview – ${db.company.name}` : `${db.company.name} – ${v.name}`) + (model.value.scope.label ? ` · Scope: ${model.value.scope.label}` : ''),
  footer: `${db.company.name} · ${v.name} · EA Compass · ${today}`
})
const svg = computed(() => svgOf(view.value))
const scopeApps = computed(() => model.value.scope.appIds)
const trans = computed(() => transitions(scopeApps.value))
const currentChange = computed(() => view.value.kind === 'plateau' && view.value.plateauIdx > 0 ? trans.value[view.value.plateauIdx - 1] : null)

// ---- exports
const slug = s => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const fileBase = (v, i) => `${String(i + 1).padStart(2, '0')}-${slug(v.name)}`
const busy = ref('')
const message = ref('')
function flash (m) { message.value = m; setTimeout(() => (message.value = ''), 3500) }

function exportXml () {
  download(new Blob([modelToOpenExchangeXml(model.value)], { type: 'application/xml' }), `${slug(db.company.name)}-architecture-states.xml`)
}
const drawioXml = () => toDrawio(statesToDrawioPages(model.value, { showStatus: showStatus.value, company: db.company.name, date: today }))
function exportDrawio () {
  download(new Blob([drawioXml()], { type: 'application/xml' }), `${slug(db.company.name)}-architecture-states.drawio`)
}
function exportSvg () {
  const i = model.value.views.indexOf(view.value)
  download(new Blob([svg.value], { type: 'image/svg+xml' }), `${fileBase(view.value, i)}.svg`)
}
async function exportPng () {
  busy.value = 'png'
  try {
    const i = model.value.views.indexOf(view.value)
    download(await svgToPng(svg.value), `${fileBase(view.value, i)}.png`)
  } finally { busy.value = '' }
}
async function exportZip () {
  busy.value = 'zip'
  try {
    const JSZip = (await import('jszip')).default
    const zip = new JSZip()
    const base = slug(db.company.name)
    zip.file(`${base}-architecture-states.xml`, modelToOpenExchangeXml(model.value))
    zip.file(`${base}-architecture-states.drawio`, drawioXml())
    zip.file('changes-between-plateaus.csv', '\uFEFF' + changesCsv(scopeApps.value))
    for (const [i, v] of model.value.views.entries()) {
      const s = svgOf(v)
      zip.file(`svg/${fileBase(v, i)}.svg`, s)
      zip.file(`png/${fileBase(v, i)}.png`, await svgToPng(s))
    }
    zip.file('README.txt', [
      `${db.company.name} – architecture states (baseline, transitions, target)`,
      `Generated by EA Compass on ${today}.`,
      '',
      `${base}-architecture-states.xml  ArchiMate 3.x Open Exchange model with ${model.value.views.length} views.`,
      '                                    Import in Archi: File > Import > Open Exchange XML Model.',
      `${base}-architecture-states.drawio  draw.io / diagrams.net file, one page per view (ArchiMate 3 shapes, editable).`,
      'svg/, png/                          One image per view (PNG at 2x resolution for slides).',
      'changes-between-plateaus.csv        Applications introduced, phased out and retired per transition.'
    ].join('\r\n'))
    download(await zip.generateAsync({ type: 'blob' }), `${base}-architecture-states.zip`)
  } finally { busy.value = '' }
}
function printAll () { window.print() }

function saveToModeler () {
  const ds = modelToDiagrams(model.value)
  ds.forEach(saveDiagram)
  flash(`${ds.length} views saved to the ArchiMate Modeler`)
}
</script>

<template>
  <div class="no-print">
    <PageHead eyebrow="Phase E/F – Transition Architectures" title="Transition Views" color="var(--c-implementation)"
              subtitle="Baseline, transition and target architectures as ArchiMate views – generated from the roadmap and ready to export for steering committees, architecture boards or Archi." />

    <div class="card">
      <div class="row between" style="gap:12px">
        <div class="row">
          <span class="subtle strong">Scope</span>
          <button class="chip" :style="!scopeIds.length ? { background: '#eff4ff', borderColor: '#2563eb' } : null" @click="scopeIds = []">All domains</button>
          <button v-for="c in l1Caps()" :key="c.id" class="chip" :style="scopeIds.includes(c.id) ? { background: '#fef3c7', borderColor: '#e0a100' } : null" @click="toggleScope(c.id)">{{ c.name }}</button>
        </div>
        <div class="row small">
          <label class="row"><input v-model="onlyChanges" type="checkbox" /> Only capabilities that change</label>
          <label class="row"><input v-model="showStatus" type="checkbox" /> Highlight changes</label>
          <label class="row"><input v-model="showRemoved" type="checkbox" :disabled="!showStatus" /> Show retired</label>
        </div>
      </div>
    </div>

    <div class="card mt exportbar">
      <span class="subtle strong">Export</span>
      <button class="btn primary" :disabled="!!busy" @click="exportZip"><Package :size="15" />{{ busy === 'zip' ? 'Packing…' : 'Download all (ZIP)' }}</button>
      <button class="btn" title="One ArchiMate model with all views – opens in Archi, BiZZdesign, Sparx" @click="exportXml"><FileCode2 :size="15" />ArchiMate model (.xml)</button>
      <button class="btn" title="draw.io / diagrams.net – one page per view, editable ArchiMate 3 shapes" @click="exportDrawio"><Workflow :size="15" />draw.io</button>
      <span class="sep" />
      <span class="subtle">This view:</span>
      <button class="btn" @click="exportSvg"><Download :size="15" />SVG</button>
      <button class="btn" :disabled="!!busy" @click="exportPng"><Image :size="15" />{{ busy === 'png' ? 'Rendering…' : 'PNG' }}</button>
      <span class="sep" />
      <button class="btn" @click="printAll"><Printer :size="15" />Print / PDF</button>
      <button class="btn" @click="saveToModeler"><Shapes :size="15" />Save views to Modeler</button>
      <span v-if="message" class="tag t-green"><CheckCircle2 :size="13" />{{ message }}</span>
    </div>

    <div class="tabs mt">
      <button v-for="v in model.views" :key="v.id" class="tab" :class="{ on: view.id === v.id }" @click="active = v.id">
        <template v-if="v.kind === 'overview'">Migration overview</template>
        <template v-else>{{ db.plateaus[v.plateauIdx].name }}<span class="subtle"> · {{ fmtMonth(db.plateaus[v.plateauIdx].date) }}</span></template>
      </button>
    </div>

    <div class="grid layout-grid">
      <div class="card canvas">
        <button class="icon-btn fitbtn" :title="fit ? 'Actual size' : 'Fit to width'" @click="fit = !fit"><component :is="fit ? Maximize2 : Minimize2" :size="16" /></button>
        <div v-if="model.scopeEmpty" class="empty">No capabilities in scope{{ onlyChanges ? ' with changes' : '' }}.</div>
        <div v-else class="svgwrap" :class="{ fit }" v-html="svg" />
      </div>

      <aside class="card side">
        <template v-if="view.kind === 'overview'">
          <h3>Transitions</h3>
          <p v-if="model.scope.label" class="subtle" style="margin:2px 0 4px">Scope: {{ model.scope.label }} · {{ model.scope.appIds.size }} applications</p>
          <div v-for="t in trans" :key="t.i" class="trans">
            <div class="strong small">{{ t.from.name }} → {{ t.to.name }}</div>
            <div class="subtle">Run cost {{ money(t.runFrom) }} → {{ money(t.runTo) }}</div>
            <div class="small"><span style="color:#16a34a">+{{ t.introduced.length }} new</span> · <span style="color:#d97706">{{ t.phaseOut.length }} phase-out</span> · <span style="color:#dc2626">−{{ t.retired.length }} retired</span></div>
          </div>
        </template>
        <template v-else>
          <h3>{{ db.plateaus[view.plateauIdx].name }}</h3>
          <p class="subtle" style="margin:2px 0 10px">{{ db.plateaus[view.plateauIdx].description }}</p>
          <dl class="kv" style="grid-template-columns:110px 1fr">
            <dt>Live apps</dt><dd>{{ plateauSummary(view.plateauIdx, scopeApps).apps }}</dd>
            <dt>Run cost / yr</dt><dd>{{ money(plateauSummary(view.plateauIdx, scopeApps).runCost) }}</dd>
            <dt>In implementation</dt><dd>{{ plateauSummary(view.plateauIdx, scopeApps).planned }}</dd>
          </dl>
          <template v-if="currentChange">
            <h4 class="subtle mt" style="text-transform:uppercase;letter-spacing:.05em">Since {{ currentChange.from.name }}</h4>
            <div v-if="currentChange.introduced.length" class="mt small strong" style="color:#16a34a">Introduced</div>
            <div class="row" style="margin-top:4px"><EntityChip v-for="a in currentChange.introduced" :key="a.id" type="application" :id="a.id" /></div>
            <div v-if="currentChange.phaseOut.length" class="mt small strong" style="color:#d97706">Phase-out started</div>
            <div class="row" style="margin-top:4px"><EntityChip v-for="a in currentChange.phaseOut" :key="a.id" type="application" :id="a.id" /></div>
            <div v-if="currentChange.retired.length" class="mt small strong" style="color:#dc2626">Retired</div>
            <div class="row" style="margin-top:4px"><EntityChip v-for="a in currentChange.retired" :key="a.id" type="application" :id="a.id" /></div>
            <div v-if="!currentChange.introduced.length && !currentChange.retired.length && !currentChange.phaseOut.length" class="empty">No application changes.</div>
          </template>
          <p v-else class="subtle mt">The baseline is the starting point – changes are shown from Transition 1 on.</p>
        </template>
      </aside>
    </div>
  </div>

  <!-- print: every view on its own landscape page -->
  <div class="print-only">
    <div v-for="v in model.views" :key="v.id" class="print-page" v-html="svgOf(v)" />
  </div>
</template>

